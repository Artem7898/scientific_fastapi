def student_t_critical(confidence_level: float, degrees_of_freedom: int) -> float:
    """Return a two-sided critical value for 8..50 statistical units.

    This quantile does not establish that units are independent or normally
    distributed; those statistical conditions belong to the calling estimator.
    """
    if (
        confidence_level not in _CONFIDENCE_LEVELS
        or type(degrees_of_freedom) is not int
        or not 7 <= degrees_of_freedom <= 49
    ):
        raise ValueError("Unsupported Student-t confidence level or degrees of freedom")
    return _STUDENT_T_CRITICAL[degrees_of_freedom - 7][_CONFIDENCE_LEVELS.index(confidence_level)]
